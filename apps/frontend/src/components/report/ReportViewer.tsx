import type { ReactNode } from "react";

import type { AnalyzeRepositoryResponse } from "../../types/report";

import ArchitectureCard from "./ArchitectureCard";
import CachedResultNotice from "./CachedResultNotice";
import CodeQualityCard from "./CodeQualityCard";
import FolderStructureCard from "./FolderStructureCard";
import ImprovementCard from "./ImprovementCard";
import InterviewQuestionsCard from "./InterviewQuestionsCard";
import MarkdownDownload from "./MarkdownDownload";
import ReportGrid from "./ReportGrid";
import ResumeFeedbackCard from "./ResumeFeedbackCard";
import StrengthsCard from "./StrengthsCard";
import SummaryCard from "./SummaryCard";
import TechnologyStackCard from "./TechnologyStackCard";
import WeaknessesCard from "./WeaknessesCard";

interface Props {
  result: Pick<
    AnalyzeRepositoryResponse,
    "report" | "markdown" | "repository" | "analyzedAt"
  > & { cached?: boolean };
  loading?: boolean;
  /** Offered on cached results; omitted on shared-report pages. */
  onReanalyze?(): void;
  /** Extra header actions, e.g. the Share controls. */
  actions?: ReactNode;
}

export default function ReportViewer({
  result,
  loading = false,
  onReanalyze,
  actions,
}: Props) {
  const { report, markdown, repository } = result;

  return (
    <div className="space-y-10">

      {result.cached && onReanalyze && (
        <CachedResultNotice
          analyzedAt={result.analyzedAt}
          loading={loading}
          onReanalyze={onReanalyze}
        />
      )}

      <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">

        <div>

          <h2 className="text-3xl font-bold">
            Engineering Review
          </h2>

          <p className="mt-2 text-slate-500">
            {repository.url ? (
              <a
                href={repository.url}
                target="_blank"
                rel="noreferrer"
                className="font-medium text-blue-600 hover:underline"
              >
                {repository.name}
              </a>
            ) : (
              <span className="font-medium text-slate-700">
                {repository.name}
              </span>
            )}
            {repository.ref && <> · {repository.ref}</>}
            {repository.commitSha && (
              <>
                {" @ "}
                <code className="rounded bg-slate-100 px-1.5 py-0.5 text-xs">
                  {repository.commitSha.slice(0, 7)}
                </code>
              </>
            )}
            {" · Generated by RepoInsight-AI"}
          </p>

        </div>

        <div className="flex flex-col gap-3 sm:items-end">
          <MarkdownDownload
            markdown={markdown}
          />

          {actions}
        </div>

      </div>

      <ReportGrid>
        <SummaryCard report={report} />
        <TechnologyStackCard report={report} />
      </ReportGrid>

      <ReportGrid>
        <ArchitectureCard report={report} />
        <FolderStructureCard report={report} />
      </ReportGrid>

      <ReportGrid>
        <CodeQualityCard report={report} />
        <ResumeFeedbackCard report={report} />
      </ReportGrid>

      <ReportGrid>
        <StrengthsCard report={report} />
        <WeaknessesCard report={report} />
      </ReportGrid>

      <div className="space-y-6">

        <h2 className="text-2xl font-bold">
          Recommended Improvements
        </h2>

        {report.improvements.map(
          (item) => (
            <ImprovementCard
              key={item.title}
              {...item}
            />
          ),
        )}

      </div>

      <InterviewQuestionsCard
        report={report}
      />

    </div>
  );
}